using System;
using System.Collections.Generic;

namespace ExcelPowerTools.Core.IoPipeline.SwpBridge
{
    /// <summary>What a producer is handed. Sources are resolved lazily by NAME so a producer never
    /// knows a path, and a workspace that never pointed at a CSV simply gets null back.</summary>
    public sealed class SwpGeneratorContext
    {
        public SwpPlantType PlantType;
        public IReadOnlyList<IoRowData> IoRows;

        /// <summary>"Sensor" / "StrobeDevice" → the file's lines, or null when it is not loaded.</summary>
        public Func<string, string[]> ReadSource;

        public IReadOnlyList<SwpStrobeTemplate> StrobeTemplates;
        public List<SwpLogEntry> Log;

        internal string[] Source(string name) =>
            ReadSource == null || string.IsNullOrEmpty(name) ? null : ReadSource(name);
    }

    /// <summary>
    /// The one place ad-hoc mnemonic logic lives.
    ///
    /// Most mnemonics are answered declaratively — a regex and a destination in the mnemonic map.
    /// A few cannot be: belt photocells exist because Sensor.csv says so, are assigned to belts by
    /// PREV_BELT_ID, ordered by their position along the belt, and only then given a name that is
    /// sought back in the IO list for its address and electrical identity. No regex over a name
    /// expresses that, and stretching the table until it could would make every simple rule pay
    /// for the hardest one.
    ///
    /// So the bespoke logic stays code, and this class is its REGISTRY: a `generate:Name` row in
    /// the _Mnemonics sheet is a pointer, this is what it points at. Two properties are the point
    /// of doing it this way — every custom behaviour is discoverable in one file, and a row naming
    /// a producer that does not exist is an ERROR rather than a silent no-op, so a typo in the
    /// sheet cannot quietly stop a plant's photocell alarms from being generated.
    ///
    /// Adding a behaviour: write the method, register it below, add the row. Nothing else moves.
    /// </summary>
    public static class CustomMnemonicsManager
    {
        public delegate List<DiagnosticEntry> Producer(SwpMnemonicRule rule, SwpGeneratorContext context);

        private static readonly Dictionary<string, Producer> Registry =
            new Dictionary<string, Producer>(StringComparer.OrdinalIgnoreCase)
            {
                ["Photocells"] = Photocells,
                ["Strobes"] = Strobes,
            };

        /// <summary>The registered names, for the setup form and the sheet's validation.</summary>
        public static IEnumerable<string> Names => Registry.Keys;

        public static bool Has(string name) =>
            !string.IsNullOrEmpty(name) && Registry.ContainsKey(name);

        /// <summary>
        /// Runs every enabled producer the map declares for this plant, in table order. A row
        /// naming an unregistered producer is reported and skipped — the build continues, because
        /// one bad row must not cost the other producers, but it is never silent.
        /// </summary>
        public static List<DiagnosticEntry> RunAll(SwpMnemonicMap map, SwpGeneratorContext context)
        {
            var produced = new List<DiagnosticEntry>();
            if (map == null || context == null) return produced;

            foreach (SwpMnemonicRule rule in map.Generators(context.PlantType))
            {
                if (!Registry.TryGetValue(rule.Generator, out Producer producer))
                {
                    context.Log?.Add(SwpLogEntry.For(SwpLogSeverity.Error,
                        "the mnemonic map names a custom producer \"" + rule.Generator +
                        "\" that does not exist — nothing was generated for it (known producers: " +
                        string.Join(", ", new List<string>(Registry.Keys).ToArray()) + ")"));
                    continue;
                }

                List<DiagnosticEntry> entries = producer(rule, context) ?? new List<DiagnosticEntry>();
                produced.AddRange(entries);
                context.Log?.Add(SwpLogEntry.For(SwpLogSeverity.Info,
                    entries.Count + " mnemonic(s) generated by " + rule.Generator));
            }
            return produced;
        }

        // ---- the producers ------------------------------------------------------------------

        private static List<DiagnosticEntry> Photocells(SwpMnemonicRule rule, SwpGeneratorContext context)
        {
            string[] lines = context.Source(rule.Param("source", "Sensor"));
            if (lines == null)
            {
                context.Log?.Add(SwpLogEntry.For(SwpLogSeverity.Info,
                    "no " + rule.Param("source", "Sensor") +
                    " file in this workspace — no belt-photocell alarms were generated"));
                return new List<DiagnosticEntry>();
            }
            return SwpUpsGenerators.GeneratePhotocellAlarms(lines, context.IoRows, context.Log, rule);
        }

        private static List<DiagnosticEntry> Strobes(SwpMnemonicRule rule, SwpGeneratorContext context)
        {
            string[] lines = context.Source(rule.Param("source", "StrobeDevice"));
            if (lines == null || context.StrobeTemplates == null || context.StrobeTemplates.Count == 0)
                return new List<DiagnosticEntry>();
            return SwpUpsGenerators.GenerateStrobeAlarms(lines, context.StrobeTemplates, context.Log);
        }
    }
}
