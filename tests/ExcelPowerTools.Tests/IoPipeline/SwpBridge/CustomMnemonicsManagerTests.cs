using System.Collections.Generic;
using System.Linq;
using ExcelPowerTools.Core.IoPipeline.SwpBridge;
using Xunit;

namespace ExcelPowerTools.Tests.IoPipeline.SwpBridge
{
    /// <summary>
    /// The custom-producer registry. A `generate:Name` row in the mnemonic map is a POINTER; this
    /// is what it points at. The two properties worth protecting: every ad-hoc behaviour is
    /// discoverable in one place, and a row naming a producer that does not exist is an ERROR —
    /// a typo in the sheet must never quietly stop a plant's alarms from being generated.
    /// </summary>
    public class CustomMnemonicsManagerTests
    {
        private static SwpMnemonicMap MapWith(params SwpMnemonicRule[] rules)
        {
            var map = new SwpMnemonicMap();
            map.Rules.AddRange(rules);
            return map;
        }

        private static SwpMnemonicRule Producer(string name, bool enabled = true) =>
            new SwpMnemonicRule
            {
                PlantType = SwpPlantType.Ups,
                Order = 200,
                Enabled = enabled,
                Kind = SwpRuleKind.Generate,
                Generator = name,
                ObjectKey = "BELT",
            };

        private static SwpGeneratorContext Context(List<SwpLogEntry> log, string[] sensorLines = null) =>
            new SwpGeneratorContext
            {
                PlantType = SwpPlantType.Ups,
                IoRows = new List<IoRowData>(),
                StrobeTemplates = new List<SwpStrobeTemplate>(),
                Log = log,
                ReadSource = name => name == "Sensor" ? sensorLines : null,
            };

        [Fact]
        public void The_shipped_map_only_names_producers_that_exist()
        {
            // The guard that keeps the table and the registry from drifting apart.
            SwpMnemonicMap official = SwpMnemonicMapDefaults.Official();
            foreach (SwpPlantType plant in (SwpPlantType[])System.Enum.GetValues(typeof(SwpPlantType)))
                foreach (SwpMnemonicRule rule in official.Generators(plant))
                    Assert.True(CustomMnemonicsManager.Has(rule.Generator),
                        "no producer registered for \"" + rule.Generator + "\"");
        }

        [Fact]
        public void Both_shipped_producers_are_declared_for_upstream()
        {
            List<SwpMnemonicRule> producers =
                SwpMnemonicMapDefaults.Official().Generators(SwpPlantType.Ups);

            Assert.Contains(producers, r => r.Generator == "Photocells");
            Assert.Contains(producers, r => r.Generator == "Strobes");
            // A sorter has none — its alarms all come from the IO list.
            Assert.Empty(SwpMnemonicMapDefaults.Official().Generators(SwpPlantType.Msc));
        }

        [Fact]
        public void A_dangling_pointer_is_an_error_and_the_others_still_run()
        {
            var log = new List<SwpLogEntry>();
            CustomMnemonicsManager.RunAll(
                MapWith(Producer("Photocellz"), Producer("Photocells")), Context(log));

            SwpLogEntry error = log.Single(l => l.Severity == SwpLogSeverity.Error);
            Assert.Contains("Photocellz", error.Message);
            Assert.Contains("does not exist", error.Message);
            // …and it names what IS available, so the fix is obvious from the log alone.
            Assert.Contains("Photocells", error.Message);
            // The good row still reported its (empty) result rather than being skipped.
            Assert.Contains(log, l => l.Message.Contains("generated by Photocells"));
        }

        [Fact]
        public void An_unticked_producer_does_not_run()
        {
            var log = new List<SwpLogEntry>();
            CustomMnemonicsManager.RunAll(MapWith(Producer("Photocells", enabled: false)), Context(log));

            Assert.DoesNotContain(log, l => l.Message.Contains("generated by"));
        }

        [Fact]
        public void A_producer_whose_source_is_absent_says_so_and_generates_nothing()
        {
            var log = new List<SwpLogEntry>();
            List<DiagnosticEntry> produced =
                CustomMnemonicsManager.RunAll(MapWith(Producer("Photocells")), Context(log));

            Assert.Empty(produced);
            Assert.Contains(log, l => l.Message.Contains("no Sensor file"));
        }

        [Fact]
        public void The_producer_row_supplies_the_constants_it_declares()
        {
            // One belt, one photocell: the emitted name, first bit, marker and T.S. ref all come
            // from the row rather than from constants buried in the generator.
            string[] sensor =
            {
                ";@;PREV_BELT_ID;1;x;7;x;5",
                ";@;OFFSET_ON_BELT_Y;1;x;7;x;1200",
            };
            var rule = Producer("Photocells");
            rule.Emit = "ALLB_{sys}_{belt:000}_{bit:00}";
            rule.Params = "source=Sensor;firstBit=60;mark=XX;tsRef=TS_099;desc=Cell {sensor}";

            var log = new List<SwpLogEntry>();
            List<DiagnosticEntry> produced =
                CustomMnemonicsManager.RunAll(MapWith(rule), Context(log, sensor));

            DiagnosticEntry entry = Assert.Single(produced);
            Assert.Equal("ALLB_1_005_60", entry.Mnemonic);
            Assert.Equal("XX", entry.GeneratedBy);
            Assert.Equal("TS_099", entry.TsRef);
            Assert.Equal("Cell 1", entry.Desc1A);
        }

        [Fact]
        public void The_shipped_constants_still_apply_when_the_row_declares_none()
        {
            string[] sensor =
            {
                ";@;PREV_BELT_ID;1;x;7;x;5",
                ";@;OFFSET_ON_BELT_Y;1;x;7;x;1200",
            };
            var log = new List<SwpLogEntry>();
            List<DiagnosticEntry> produced = CustomMnemonicsManager.RunAll(
                MapWith(SwpMnemonicMapDefaults.Official()
                    .Generators(SwpPlantType.Ups)
                    .Single(r => r.Generator == "Photocells")),
                Context(log, sensor));

            DiagnosticEntry entry = Assert.Single(produced);
            Assert.Equal("ALLB_1_005_50", entry.Mnemonic);   // firstBit 50
            Assert.Equal("AP", entry.GeneratedBy);
            Assert.Equal("TS_031", entry.TsRef);
            Assert.Equal("Sensor Fault #1", entry.Desc1A);
        }

        [Fact]
        public void A_generate_row_never_claims_an_incoming_mnemonic()
        {
            // Producers CREATE names; they must not compete with the map rules that place them.
            SwpMnemonicMap map = MapWith(Producer("Photocells"));
            Assert.Null(map.RuleFor("ALLB_1_005_50", SwpPlantType.Ups));
        }

        [Fact]
        public void A_generate_row_survives_the_text_round_trip()
        {
            SwpMnemonicMap official = SwpMnemonicMapDefaults.Official();
            SwpMnemonicMap reparsed = SwpMnemonicMap.Parse(official.ToLines(), null);

            SwpMnemonicRule photocells =
                reparsed.Generators(SwpPlantType.Ups).Single(r => r.Generator == "Photocells");
            Assert.Equal(SwpRuleKind.Generate, photocells.Kind);
            Assert.Equal("ALLB_{sys}_{belt:000}_{bit:00}", photocells.Emit);
            Assert.Equal("50", photocells.Param("firstBit"));
            // The description keeps its spaces — which is why Params is semicolon-separated.
            Assert.Equal("Sensor Fault #{sensor}", photocells.Param("desc"));
        }

        [Fact]
        public void A_generate_row_with_no_producer_name_is_inert_with_a_reason()
        {
            var log = new List<SwpLogEntry>();
            SwpMnemonicMap map = SwpMnemonicMap.Parse(new[]
            {
                // Set Plant Order On Kind Object Match … — the leading tab is an empty Set.
                "\tUps\t200\tx\tgenerate\tBELT\t\t\t\t\t\t\t\t\t",
            }, log);

            Assert.Contains(log, l => l.Message.Contains("inert"));
            Assert.Empty(map.Generators(SwpPlantType.Ups));
        }
    }
}
